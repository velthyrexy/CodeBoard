    fun getSuggestions(
        language: String,
        prefix: String,
        limit: Int = 4
    ): List<Suggestion> {

        val source =
            keywordsByLanguage[language]
                ?: keywordsByLanguage["Luau"]
                ?: emptyList()

        if (source.isEmpty()) {
            return emptyList()
        }

        val query =
            prefix.trim()

        if (query.isBlank()) {
            return source
                .sortedByDescending { it.popularity }
                .take(limit)
        }

        val normalizedQuery =
            query.lowercase()

        val exact =
            source.filter {
                it.text.equals(
                    query,
                    ignoreCase = true
                )
            }

        val prefixMatches =
            source.filter {
                it.text.startsWith(
                    query,
                    ignoreCase = true
                )
            }

        val containsMatches =
            source.filter {
                !it.text.startsWith(
                    query,
                    ignoreCase = true
                ) &&
                    it.text.contains(
                        normalizedQuery,
                        ignoreCase = true
                    )
            }

        return (exact + prefixMatches + containsMatches)
            .distinctBy {
                it.text.lowercase()
            }
            .sortedWith(
                compareByDescending<Suggestion> {
                    it.text.equals(
                        query,
                        ignoreCase = true
                    )
                }.thenByDescending {
                    it.text.startsWith(
                        query,
                        ignoreCase = true
                    )
                }.thenByDescending {
                    it.popularity
                }
            )
            .take(limit)
    }

    private fun s(
        text: String,
        type: String,
        popularity: Int
    ): Suggestion {
        return Suggestion(
            text = text,
            type = type,
            popularity = popularity
        )
    }
